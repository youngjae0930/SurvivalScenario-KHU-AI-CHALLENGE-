const sourceId = (id: string) => id.replace(/^companion:/, '')
export function companionOpinion(choice: CatalogChoice, fallback: string) {
  return lines[sourceId(choice.id)] ?? fallback
}
export function companionHesitation(reason: string) {
  return reason === 'no-available-choice' ? '동료가 주변을 살핀다. “지금은 떠오르는 방법이 없어. 조금만 더 생각해 보자.”'
    : reason === 'resource-tradeoff' ? '동료가 열린 배낭을 내려다본다. “하나를 쓰면 다른 게 부족해지겠네. 어느 쪽도 쉽게 고르기는 어려워.”'
      : '동료가 두 길을 번갈아 본다. “어느 쪽이 나을지 확신이 안 서. 네 생각도 듣고 싶어.”'
}
export function relationshipSummary(change: { before: number; after: number }) {
  return change.after > change.before ? '이번 결과로 동료의 신뢰가 조금 높아졌다.'
    : change.after < change.before ? '이번 일을 겪으며 동료의 마음에 불안과 망설임이 남았다.'
      : '마음에 걸리는 점은 남아 있지만, 둘은 다음 길을 함께 살핀다.'
}
